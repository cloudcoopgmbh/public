Import-Module ActiveDirectory

$ServiceAccount = "<YourServiceAccount>" # e.g. "domain\syncserviceaccount"
$Sid = (New-Object System.Security.Principal.NTAccount($ServiceAccount)).Translate([System.Security.Principal.SecurityIdentifier])

$RightsReplicateChanges          = [Guid]"1131f6aa-9c07-11d1-f79f-00c04fc2dcd2" # DS-Replication-Get-Changes
$RightsReplicateChangesAll       = [Guid]"1131f6ad-9c07-11d1-f79f-00c04fc2dcd2" # DS-Replication-Get-Changes-All
$RightsReplicateChangesFiltered  = [Guid]"89e95b76-444d-4c62-991a-0facbeda640c" # DS-Replication-Get-Changes-In-Filtered-Set

$DefaultNC = "LDAP://" + (Get-ADRootDSE).defaultNamingContext
$ConfigNC  = "LDAP://" + (Get-ADRootDSE).configurationNamingContext
# $SchemaNC  = "LDAP://" + (Get-ADRootDSE).schemaNamingContext  # optional

function Add-ExtendedRight {
    param([string]$LdapPath, [Guid]$RightGuid)
    $entry = New-Object System.DirectoryServices.DirectoryEntry($LdapPath)
    $acl = $entry.ObjectSecurity
    $idRef = New-Object System.Security.Principal.SecurityIdentifier($Sid.Value)
    $ace = New-Object System.DirectoryServices.ActiveDirectoryAccessRule(
        $idRef,
        [System.DirectoryServices.ActiveDirectoryRights]::ExtendedRight,
        [System.Security.AccessControl.AccessControlType]::Allow,
        $RightGuid
    )
    $acl.AddAccessRule($ace) | Out-Null
    $entry.ObjectSecurity = $acl
    $entry.CommitChanges()
    Write-Host "Granted $RightGuid on $LdapPath to $ServiceAccount"
}

foreach($nc in @($DefaultNC, $ConfigNC)) {
    Add-ExtendedRight -LdapPath $nc -RightGuid $RightsReplicateChanges
    Add-ExtendedRight -LdapPath $nc -RightGuid $RightsReplicateChangesAll
    Add-ExtendedRight -LdapPath $nc -RightGuid $RightsReplicateChangesFiltered
}

Write-Host "Done. Trigger a delta sync." -ForegroundColor Green
